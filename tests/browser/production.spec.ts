import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { readFileSync } from 'node:fs';
import type { Page } from '@playwright/test';
const fixture=()=>JSON.parse(readFileSync('.e2e/fixture.json','utf8'));
async function login(page:Page,role:string) {
  const data=fixture();
  await page.goto('/');
  await page.getByLabel('Número de empleado').fill(data.accounts[role].employee);
  await page.getByLabel('Contraseña',{exact:true}).fill(data.password);
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await expect(page.getByText('Gulliver',{exact:true})).toBeVisible();
}
test('capture survives offline reload, synchronizes once and supervisor closes the shift',async({page,browser})=>{
  const data=fixture();
  const consoleErrors:string[]=[];
  page.on('pageerror',error=>consoleErrors.push(error.message));
  await login(page,'Operador');
  await page.getByLabel('Preparar plan publicado').selectOption(data.plan_id);
  await expect(page.getByRole('heading',{name:'Captura del intervalo'})).toBeVisible();
  await page.evaluate(async()=>{
    await navigator.serviceWorker.ready;
    if(!navigator.serviceWorker.controller) await new Promise<void>(resolve=>navigator.serviceWorker.addEventListener('controllerchange',()=>resolve(),{once:true}));
  });
  await page.context().setOffline(true);
  await page.reload();
  await expect(page.getByText('Sin conexión',{exact:false}).first()).toBeVisible();
  await page.getByLabel('Piezas buenas',{exact:true}).fill('52');
  await page.getByRole('button',{name:'Agregar scrap, paro o falla'}).click();
  await page.getByRole('combobox',{name:'Motivo',exact:true}).selectOption(data.scrap_id);
  await page.getByLabel('Piezas',{exact:true}).fill('3');
  await page.getByRole('button',{name:'Guardar captura en este dispositivo'}).click();
  await expect(page.locator('.status')).toContainText('1 envíos pendientes');
  await page.reload();
  await expect(page.getByLabel('Piezas buenas',{exact:true})).toHaveValue('52');
  await expect(page.getByLabel('Piezas',{exact:true})).toHaveValue('3');
  await page.getByLabel('Verifiqué los intervalos y las cantidades del turno.').check();
  await page.getByRole('button',{name:'Enviar turno a revisión al recuperar conexión'}).click();
  await expect(page.locator('.status')).toContainText('2 envíos pendientes');
  await page.context().setOffline(false);
  await expect(page.locator('.status')).toContainText('Enviado a revisión · Confirmado por servidor',{timeout:30000});
  await page.screenshot({path:'test-results/capture-landscape.png',fullPage:true});
  await page.setViewportSize({width:768,height:1024});
  await page.screenshot({path:'test-results/capture-portrait.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const axe=await new AxeBuilder({page}).analyze();
  expect(axe.violations).toEqual([]);
  const supervisor=await browser.newContext({viewport:{width:1024,height:768}});
  const review=await supervisor.newPage();
  await login(review,'Supervisor');
  await review.getByLabel('Consultar turno del servidor').selectOption(data.plan_id);
  await expect(review.getByLabel('Piezas buenas',{exact:true})).toHaveValue('52');
  await review.getByLabel('Revisé la captura completa y autorizo el cierre.').check();
  await review.getByRole('button',{name:'Autorizar cierre definitivo'}).click();
  await expect(review.locator('.status')).toContainText('Cerrado · Confirmado por servidor',{timeout:30000});
  await page.getByRole('button',{name:'Actualizar turno del servidor'}).click();
  await expect(page.locator('.status')).toContainText('Cerrado · Confirmado por servidor');
  await expect(page.getByLabel('Piezas buenas',{exact:true})).toBeDisabled();
  await review.getByRole('button',{name:'Consultar historial de cambios'}).click();
  await expect(review.getByRole('cell',{name:'Cierre',exact:true})).toBeVisible();
  expect(consoleErrors).toEqual([]);
  await supervisor.close();
  const adminContext=await browser.newContext();
  const admin=await adminContext.newPage();
  await login(admin,'Administrador');
  await admin.getByRole('button',{name:'Resultados',exact:true}).click();
  const scoped=admin.waitForResponse(r=>r.url().includes('/analytics/summary') && new URL(r.url()).searchParams.get('plant_id')===data.plant_id);
  await admin.getByRole('combobox',{name:'Planta',exact:true}).selectOption(data.plant_id);
  expect((await scoped).ok()).toBe(true);
  await expect(admin.getByRole('cell',{name:'52',exact:true})).toBeVisible();
  await adminContext.close();
});
